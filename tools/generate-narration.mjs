import {readFileSync,writeFileSync,mkdirSync,renameSync,existsSync,readdirSync,unlinkSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
import {KOKORO} from './narration-config.mjs';
import {inspectMp3} from './mp3.mjs';
const require=createRequire(import.meta.url),{KokoroTTS}=require('kokoro-js');
const kokoroRequire=createRequire(require.resolve('kokoro-js')),{env}=kokoroRequire('@huggingface/transformers');
const root=new URL('../',import.meta.url),output=new URL('dist/audio/narration/',root),manifestPath=new URL('dist/narration.js',root);
const hash=value=>createHash('sha256').update(value).digest('hex');
const context=vm.createContext({});vm.runInContext(readFileSync(new URL('dist/course.js',root),'utf8'),context);
const lessons=vm.runInContext('COURSE',context);
let previous={chapters:[]};
if(existsSync(manifestPath))previous=vm.runInNewContext(readFileSync(manifestPath,'utf8')+'\nNARRATION;');
const manifest={version:1,chapters:lessons.map(()=>[])};
const save=()=>{const temp=fileURLToPath(manifestPath)+'.tmp';writeFileSync(temp,'// Generated by pnpm narrate. Keep recordings and captions in sync.\nconst NARRATION = '+JSON.stringify(manifest,null,2)+';\n');renameSync(temp,manifestPath);};
mkdirSync(output,{recursive:true});
env.allowRemoteModels=false;env.localModelPath=new URL('tools/models/',root).pathname;
let model,generated=0,reused=0;
for(const lesson of lessons){
  for(let segment=0;segment<lesson.story.length;segment++){
    const text=lesson.story[segment];
    if(text.includes('{name}'))throw new Error('Narration scripts must be the same for every learner');
    const sourceHash=hash(JSON.stringify({text,...KOKORO,format:'mp3-mono-24000-64k-v1'}));
    const existing=previous.chapters?.[lesson.id-1]?.[segment];
    if(existing?.sourceHash===sourceHash&&existsSync(new URL('dist/'+existing.src,root))&&hash(readFileSync(new URL('dist/'+existing.src,root)))===existing.sha256){
      manifest.chapters[lesson.id-1][segment]=existing;reused++;save();continue;
    }
    if(!model){console.log('Loading the offline narration generator…');model=await KokoroTTS.from_pretrained('kokoro',{device:'cpu',dtype:KOKORO.dtype});}
    const audio=await model.generate(text,{voice:KOKORO.voice,speed:KOKORO.speed});
    const samples=audio.audio;
    let energy=0;for(const value of samples){if(!Number.isFinite(value))throw new Error('Invalid speech sample');energy+=value*value;}
    if(samples.length<24000||Math.sqrt(energy/samples.length)<.001)throw new Error('Speech is too short or silent');
    const temporary=new URL('pending.mp3',output);
    execFileSync(process.env.FFMPEG||'ffmpeg',['-hide_banner','-loglevel','error','-f','f32le','-ar',String(audio.sampling_rate),'-ac','1','-i','pipe:0','-codec:a','libmp3lame','-b:a','64k','-ar','24000','-ac','1','-map_metadata','-1','-id3v2_version','0','-write_xing','0','-y',fileURLToPath(temporary)],{input:Buffer.from(samples.buffer,samples.byteOffset,samples.byteLength)});
    const bytes=readFileSync(temporary),sha256=hash(bytes),info=inspectMp3(bytes);
    const name=`chapter-${String(lesson.id).padStart(2,'0')}-part-${segment+1}.${sha256.slice(0,12)}.mp3`;
    renameSync(temporary,new URL(name,output));
    manifest.chapters[lesson.id-1][segment]={text,src:'audio/narration/'+name,duration:info.duration,bytes:bytes.length,sha256,sourceHash};
    generated++;save();
    console.log(`Ready ${lesson.id*6-6+segment+1}/156: chapter ${lesson.id}, part ${segment+1} (${info.duration.toFixed(1)}s, ${(bytes.length/1024).toFixed(0)} KB)`);
  }
}
const used=new Set(manifest.chapters.flat().map(clip=>clip.src.split('/').at(-1)));
for(const name of readdirSync(output))if(name.endsWith('.mp3')&&!used.has(name))unlinkSync(new URL(name,output));
save();console.log(`Complete: ${generated} generated, ${reused} reused; ${(manifest.chapters.flat().reduce((sum,clip)=>sum+clip.bytes,0)/1024/1024).toFixed(1)} MB total.`);
